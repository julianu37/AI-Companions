ENTRY_VALUE = re.compile(r'("value"\s*:\s*")((?:[^"\\]|\\.)*)(")')
ESCAPES = {'n': '\n', 'r': '\r', 't': '\t', '"': '"', '\\': '\\'}


def normalized(table):
    """Normaliza as chaves do mapa do mesmo jeito que o valor do PT (as chaves sao escritas com acento aqui,
    porque e assim que se le o arquivo)."""
    result = {}
    for key, value in table.items():
        norm = normalize(key)
        if norm in result and result[norm] != value:
            print('   AVISO: chave colidente %r (%r vs %r)' % (norm, result[norm], value))
        result[norm] = value
    return result


def unescape(text):
    return re.sub(r'\\(.)', lambda m: ESCAPES.get(m.group(1), m.group(0)), text)


def escape(text):
    return text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')


def build_ui(table):
    """Le o PT e devolve o texto com os valores trocados (mesmas chaves, ordem, indentacao e CRLF)."""
    raw = io.open(os.path.join(ROOT, UI_SOURCE), 'rb').read().decode('utf-8')
    missing = []
    unused = set(table)
    out = []
    for line in raw.split('\n'):
        m = ENTRY_VALUE.search(line)
        if not m:
            out.append(line)
            continue
        pt_value = unescape(m.group(2))
        key = normalize(pt_value)
        if key in table:
            unused.discard(key)
            translated = table[key]
        else:
            missing.append(pt_value)
            translated = pt_value
        out.append(line[:m.start(2)] + escape(translated) + line[m.end(2):])
    return '\n'.join(out), missing, sorted(unused)


def build_speech(table):
    """Le as falas do PT e devolve o texto com as linhas trocadas, categoria por categoria e na mesma ordem."""
    raw = io.open(os.path.join(ROOT, SPEECH_SOURCE), 'rb').read().decode('utf-8')
    out = []
    current = None
    index = 0
    problems = []
    problems_alignment = []
    for line in raw.split('\n'):
        stripped = line.strip()
        if stripped.endswith('[') and stripped.startswith('"'):
            current = stripped[1:stripped.index('"', 1)]
            index = 0
            problems_alignment.append(current)
            out.append(line)
            continue
        if stripped.startswith(']'):
            if current is not None:
                wanted = len(table.get(current, []))
                if wanted and wanted != index:
                    problems.append('%s: %d linhas no PT, %d na traducao' % (current, index, wanted))
            current = None
            out.append(line)
            continue
        if current is not None and stripped.startswith('"'):
            translated_lines = table.get(current, [])
            indent = line[:len(line) - len(line.lstrip())]
            comma = ',' if stripped.endswith(',') else ''
            if index < len(translated_lines):
                out.append(indent + '"' + escape(translated_lines[index]) + '"' + comma)
            else:
                problems.append('%s[%d]: sem traducao' % (current, index))
                out.append(line)
            index += 1
            continue
        out.append(line)
    return '\n'.join(out), problems


def write(path, text):
    full = os.path.join(ROOT, path)
    io.open(full, 'w', encoding='utf-8', newline='').write(text)
    print('   %s (%d chaves/linhas)' % (path, text.count('\n')))


def main():
    check_only = '--check' in sys.argv
    ok = True
    for label, ui_table, speech_table, ui_out, speech_out in [
        ('ES', normalized(ES_UI), ES_SPEECH, os.path.join('Translations', 'Spanish.json'), os.path.join('Speech', 'Spanish.json')),
        ('FR', normalized(FR_UI), FR_SPEECH, os.path.join('Translations', 'French.json'), os.path.join('Speech', 'French.json')),
    ]:
        print('== %s ==' % label)
        ui_text, missing, unused = build_ui(ui_table)
        print('   chaves sem traducao: %d%s' % (len(missing), (' -> ' + ' | '.join(missing[:8])) if missing else ''))
        if unused:
            print('   entradas do mapa que nao casaram com o PT: %d -> %s' % (len(unused), ' | '.join(unused[:8])))
        if missing:
            ok = False
        speech_text, problems = build_speech(speech_table)
        print('   falas: %d problema(s)%s' % (len(problems), (' -> ' + ' | '.join(problems)) if problems else ''))
        if problems:
            ok = False
        if not check_only and not missing and not problems:
            write(ui_out, ui_text)
            write(speech_out, speech_text)
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
