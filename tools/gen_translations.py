"""Gera as traducoes ES/FR do mod a partir do PT-BR (a fonte).

Uso:
    python tools/gen_translations.py            # escreve os 4 arquivos
    python tools/gen_translations.py --check    # so valida (nao escreve)

Por que existe: `Translations/Portuguese_Brazilian.json` e `Speech/Portuguese_Brazilian.json` sao a fonte
(o PT-BR e o idioma "de trabalho" do mod, e o EN vive embutido no codigo). Este script le os dois, troca SO os
valores/falas e grava:

    Translations/Spanish.json, Translations/French.json
    Speech/Spanish.json, Speech/French.json

Nada de estrutura e gerado a mao: cada linha do arquivo PT e reescrita com a traducao, entao as chaves, a ordem,
a indentacao, as linhas em branco e o tipo de quebra de linha saem identicos ao PT (exigencia da auditoria).
Os textos sao mapeados pelo VALOR do PT normalizado (sem acento, minusculo) - os 35 valores repetidos do PT viram
uma entrada so, o que garante a mesma traducao em todos os lugares; a normalizacao nao cria ambiguidade porque os
unicos casos que colidem (Cacar/cacar, Pescar/pescar, Coletar madeira/coletar madeira...) tem a mesma traducao.

Chaves THE SAME em PT e ES/FR de proposito (nomes de voz, strings so com placeholders) estao em ALLOWED_SAME.
"""
