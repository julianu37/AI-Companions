def normalize(text):
    """Chave do mapa: sem acento, com a caixa e os espacos originais ('Ligado' e 'LIGADO' sao textos
    diferentes na tela) e com os espacos colapsados."""
    decomposed = unicodedata.normalize('NFKD', text)
    stripped = ''.join(c for c in decomposed if not unicodedata.combining(c))
    return ' '.join(stripped.split())


